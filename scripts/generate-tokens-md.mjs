// Generates tokens.md from tokens/tokens.json.
//
// Derived, never authored. tokens/tokens.json is the source; build/css/tokens.css is
// the generated CSS view; this is the generated human view, for anyone reading the repo
// on GitHub who will not open 1,700 lines of JSON. Because it is generated it cannot
// drift from the source, which a hand-maintained second copy would.
//
// Runs as part of `npm run tokens`.
import { readFileSync, writeFileSync } from 'node:fs'

const tokens = JSON.parse(readFileSync('tokens/tokens.json', 'utf8'))

const isToken = n => n && typeof n === 'object' && '$value' in n

/** Follows {a.b.c} references to the raw value, and reports the chain. */
function resolve(ref, seen = new Set()) {
  if (typeof ref !== 'string' || !ref.startsWith('{')) return { value: ref, via: null }
  const path = ref.slice(1, -1)
  if (seen.has(path)) return { value: ref, via: 'circular' }
  seen.add(path)
  let node = tokens
  for (const key of path.split('.')) {
    node = node?.[key]
    if (node === undefined) return { value: ref, via: 'unresolved' }
  }
  if (!isToken(node)) return { value: ref, via: 'unresolved' }
  const next = resolve(node.$value, seen)
  return { value: next.value, via: path }
}

function format(v) {
  if (typeof v === 'object' && v !== null) {
    return Object.entries(v)
      .map(([k, val]) => `${k}: ${resolve(val).value}`)
      .join('<br>')
  }
  return String(v)
}

/** Depth-first walk yielding every token with its dot path. */
function* walk(node, path = []) {
  if (!node || typeof node !== 'object') return
  if (isToken(node)) {
    yield { path: path.join('.'), node }
    return
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue
    yield* walk(child, [...path, key])
  }
}

const GROUPS = [
  ['color.primitive', 'Colour primitives', 'Raw values. Never referenced directly by a component.'],
  ['color.semantic', 'Colour semantics', 'Roles. These are what components bind to.'],
  ['size.primitive', 'Size primitives', 'Spacing, radius, stroke, icon and illustration scales.'],
  ['spacing.semantic', 'Spacing semantics', 'Named layout distances.'],
  ['typography.primitive', 'Typography primitives', 'Font sizes, line heights, tracking, families and weights.'],
  ['typography.style', 'Typography styles', 'The composed text styles. Each resolves to a family, weight, size, line height and tracking.'],
  ['motion.primitive', 'Motion primitives', 'Durations in milliseconds, and easing curves.'],
  ['motion.semantic', 'Motion semantics', 'Named timings.'],
  ['responsive.primitive', 'Responsive primitives', 'Breakpoint values. See the description on deviceWidth.mobile before consuming these.'],
  ['component', 'Component tokens', null],
]

function at(path) {
  let node = tokens
  for (const key of path.split('.')) node = node?.[key]
  return node
}

const lines = []
lines.push('# Design tokens')
lines.push('')
lines.push('**Generated from `tokens/tokens.json` by `npm run tokens`. Do not edit this file.**')
lines.push('To change a value, edit `tokens/tokens.json` and regenerate. The other generated')
lines.push('view is `build/css/tokens.css`, which is what the app actually consumes.')
lines.push('')
lines.push('The `Resolves to` column follows every `{reference}` chain down to the raw value,')
lines.push('so a semantic token shows the literal it ends at as well as the primitive it points')
lines.push('through.')
lines.push('')

let total = 0
for (const [path, title, blurb] of GROUPS) {
  const node = at(path)
  if (!node) continue
  const rows = [...walk(node, [])]
  if (!rows.length) continue
  total += rows.length
  lines.push(`## ${title}`)
  lines.push('')
  lines.push(`\`${path}.*\` — ${rows.length} tokens`)
  lines.push('')
  if (blurb) { lines.push(blurb); lines.push('') }
  const groupDesc = node.$description
  if (groupDesc) { lines.push('> ' + groupDesc.replace(/\n/g, ' ')); lines.push('') }
  lines.push('| Token | Value | Resolves to | Notes |')
  lines.push('| --- | --- | --- | --- |')
  for (const { path: p, node: t } of rows) {
    const raw = typeof t.$value === 'object' ? format(t.$value) : String(t.$value)
    const r = typeof t.$value === 'object' ? { value: '', via: null } : resolve(t.$value)
    const resolved = r.via && r.via !== 'unresolved' ? `\`${r.value}\`` : (raw.startsWith('{') ? '_unresolved_' : '')
    const desc = (t.$description || '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
    lines.push(`| \`${path}.${p}\` | ${raw.startsWith('{') ? `\`${raw}\`` : `\`${raw}\``} | ${resolved} | ${desc} |`)
  }
  lines.push('')
}

lines.push('---')
lines.push('')
lines.push(`${total} tokens across ${GROUPS.filter(([p]) => at(p)).length} groups.`)
lines.push('')

writeFileSync('tokens.md', lines.join('\n'))
console.log(`tokens.md — ${total} tokens written`)
